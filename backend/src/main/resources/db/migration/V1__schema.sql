-- Schéma initial NeoFlow.
-- SQL compatible PostgreSQL 16 et H2 (MODE=PostgreSQL).

-- Référentiel des collaborateurs : source du département et de l'ancienneté (date_entree).
CREATE TABLE collaborateur (
    login        VARCHAR(50)  PRIMARY KEY,
    nom          VARCHAR(100) NOT NULL,
    departement  VARCHAR(40)  NOT NULL,
    date_entree  DATE         NOT NULL
);

CREATE TABLE demande (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type               VARCHAR(30)    NOT NULL,
    titre              VARCHAR(120)   NOT NULL,
    description        VARCHAR(4000),
    demandeur          VARCHAR(50)    NOT NULL,
    montant            NUMERIC(12, 2),
    date_debut         DATE           NOT NULL,
    date_fin           DATE,
    statut             VARCHAR(20)    NOT NULL,
    niveau_validation  INTEGER,
    departement        VARCHAR(40),
    urgent             BOOLEAN        DEFAULT FALSE NOT NULL,
    date_creation      TIMESTAMP      NOT NULL,
    date_maj           TIMESTAMP      NOT NULL,
    motif_refus        VARCHAR(500),
    CONSTRAINT ck_demande_niveau CHECK (niveau_validation IS NULL OR niveau_validation BETWEEN 1 AND 3)
);

CREATE INDEX idx_demande_statut ON demande (statut);
CREATE INDEX idx_demande_type ON demande (type);
CREATE INDEX idx_demande_demandeur ON demande (demandeur);

-- Journal d'audit : une ligne par action (CREATION, SOUMISSION, VALIDATION, REFUS, CLOTURE).
CREATE TABLE evenement_demande (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id   BIGINT       NOT NULL,
    type         VARCHAR(20)  NOT NULL,
    auteur       VARCHAR(50)  NOT NULL,
    horodatage   TIMESTAMP    NOT NULL,
    commentaire  VARCHAR(500),
    CONSTRAINT fk_evenement_demande FOREIGN KEY (demande_id) REFERENCES demande (id)
);

CREATE INDEX idx_evenement_demande ON evenement_demande (demande_id);
